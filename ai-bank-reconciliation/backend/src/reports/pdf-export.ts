import PDFDocument from 'pdfkit';
import { formatDate, formatDateTime, formatINR } from './format.js';
import type { ExportBundle } from './excel-export.js';

/**
 * Accountant PDF reports (summary + exception table). Includes company,
 * account, period, generated-at, page numbers and the mandatory footer.
 * Read-only; never includes secrets.
 */
export async function buildPdf(
  bundle: ExportBundle,
  title: string,
  rows: {
    label: string;
    sub: string | null;
    status: string;
    amount: string | null;
  }[],
): Promise<Buffer> {
  const doc = new PDFDocument({ size: 'A4', margin: 40, bufferPages: true });
  const chunks: Buffer[] = [];
  doc.on('data', (c: Buffer) => chunks.push(c));

  const footerLines = [
    'Generated by AI Bank Reconciliation Tool',
    'AI-assisted findings are advisory and require accountant review.',
  ];

  doc.fontSize(16).text(title, { underline: true });
  doc.moveDown(0.5);
  doc.fontSize(10);
  doc.text(`Company: ${bundle.companyName}`);
  doc.text(`Bank Account: ${bundle.filters['bankAccountId'] ?? 'All accounts'}`);
  doc.text(
    `Period: ${formatDate(bundle.filters['fromDate'] ?? null)} → ${formatDate(bundle.filters['toDate'] ?? null)}`,
  );
  doc.text(`Generated: ${formatDateTime(new Date())}`);
  doc.moveDown();

  doc.fontSize(12).text('Summary', { underline: true });
  doc.fontSize(10);
  for (const [k, v] of Object.entries(bundle.summary)) {
    const isMoney = /amount/i.test(k);
    doc.text(
      `${k}: ${isMoney ? formatINR(String(v)) : v}`,
      { indent: 12 },
    );
  }
  doc.moveDown();

  doc.fontSize(12).text('Exception Details', { underline: true });
  doc.moveDown(0.3);
  if (rows.length === 0) {
    doc.fontSize(10).text('No exceptions found for the selected filters.', { indent: 12 });
  }
  for (const row of rows) {
    doc.fontSize(10).text(
      `${row.label}${row.sub ? ` — ${row.sub}` : ''} [${row.status}]${
        row.amount ? ` — ${formatINR(row.amount)}` : ''
      }`,
      { indent: 12 },
    );
  }

  // Page numbers + footer on every page.
  const range = doc.bufferedPageRange();
  for (let i = range.start; i < range.start + range.count; i += 1) {
    doc.switchToPage(i);
    doc.fontSize(8).fillColor('#555');
    doc.text(footerLines[0] as string, 40, doc.page.height - 40, {
      width: doc.page.width - 80,
      align: 'left',
    });
    doc.text(footerLines[1] as string, 40, doc.page.height - 28, {
      width: doc.page.width - 80,
      align: 'left',
    });
    doc.text(
      `Page ${i - range.start + 1} of ${range.count}`,
      40,
      doc.page.height - 52,
      { width: doc.page.width - 80, align: 'right' },
    );
    doc.fillColor('#000');
  }

  return new Promise<Buffer>((resolve) => {
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.end();
  });
}

export async function buildSummaryPdf(bundle: ExportBundle): Promise<Buffer> {
  return buildPdf(bundle, 'Reconciliation Summary Report', []);
}

export async function buildExceptionPdf(bundle: ExportBundle): Promise<Buffer> {
  const EXCEPTION_STATUSES = new Set([
    'POSSIBLE_MATCH',
    'UNMATCHED',
    'AMOUNT_MISMATCH',
    'DATE_MISMATCH',
    'REVIEW_REQUIRED',
    'MISSING_IN_TALLY',
    'MISSING_IN_BANK',
  ]);
  return buildPdf(
    bundle,
    'Exception Report',
    bundle.rows
      .filter((r) => EXCEPTION_STATUSES.has(r.matchStatus))
      .slice(0, 500)
      .map((r) => ({
        label: r.party ?? r.bankDescription ?? 'Unknown',
        sub: r.bankDescription ?? r.party,
        status: `${r.matchStatus} / ${r.reviewStatus}`,
        amount: r.bankAmount ?? r.tallyAmount,
      })),
    );
}

export async function buildReviewPdf(bundle: ExportBundle): Promise<Buffer> {
  return buildPdf(
    bundle,
    'Review Summary Report',
    bundle.reviewRows.slice(0, 500).map((r) => ({
      label: r.action,
      sub: `${r.previousStatus} → ${r.newStatus}${r.comment ? ` — "${r.comment}"` : ''} by ${r.user?.name ?? 'Unknown'}`,
      status: r.newStatus,
      amount: null,
    })),
  );
}

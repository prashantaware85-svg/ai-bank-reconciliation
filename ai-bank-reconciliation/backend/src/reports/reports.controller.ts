import {
  Controller,
  Get,
  Query,
  Req,
  Res,
  UseGuards,
} from '@nestjs/common';
import { Throttle } from '@nestjs/throttler';
import type { Response } from 'express';
import { JwtAuthGuard } from '../auth/jwt-auth.guard.js';
import { RolesGuard } from '../auth/roles.guard.js';
import { CompanyQueryGuard } from '../bank-accounts/company-query.guard.js';
import { CompanyQueryDto } from '../bank-accounts/dto/company-query.dto.js';
import { buildExceptionsWorkbook, buildWorkbook } from './excel-export.js';
import {
  buildExceptionPdf,
  buildReviewPdf,
  buildSummaryPdf,
} from './pdf-export.js';
import { formatINR } from './format.js';
import {
  ReportsService,
  DashboardQueryDto,
} from './reports.service.js';

interface RequestUser {
  id: string;
}

/**
 * Reporting + dashboard APIs (Step 11). READ-ONLY: no endpoint modifies
 * accounting or review data. Company resolved through membership;
 * exports audited via AuditLog. Viewer may view/export (existing policy).
 */
@Controller('reports')
export class ReportsController {
  constructor(private readonly reportsService: ReportsService) {}

  private async summaryBundle(
    userId: string,
    query: DashboardQueryDto,
  ) {
    const dash = await this.reportsService.dashboard(
      userId,
      query.companyId,
      query,
    );
    return {
      companyName: dash.company.companyName,
      rows: [],
      aiRows: [],
      reviewRows: [],
      summary: {
        'Total Bank Transactions': dash.kpis.totalBankTransactions,
        'Total Tally Transactions': dash.kpis.totalTallyTransactions,
        'Matched': dash.kpis.matched,
        'Possible Match': dash.kpis.possibleMatch,
        'Unmatched': dash.kpis.unmatched,
        'Review Required': dash.kpis.reviewRequired,
        'Amount Mismatch': dash.kpis.amountMismatch,
        'Date Mismatch': dash.kpis.dateMismatch,
        'Missing in Tally': dash.kpis.missingInTally,
        'Missing in Bank': dash.kpis.missingInBank,
        'Pending Review': dash.kpis.pendingReview,
        'Confirmed': dash.kpis.confirmed,
        'Rejected': dash.kpis.rejected,
        'Ignored': dash.kpis.ignored,
        'Total Bank Amount': formatINR(dash.amounts.totalBank),
        'Total Tally Amount': formatINR(dash.amounts.totalTally),
        'Matched Bank Amount': formatINR(dash.amounts.matchedBank),
        'Unmatched Bank Amount': formatINR(dash.amounts.unmatchedBank),
        'Unmatched Tally Amount': formatINR(dash.amounts.unmatchedTally),
        'Matched %': dash.health.matchedPct,
        'Possible %': dash.health.possiblePct,
        'Exceptions %': dash.health.exceptionsPct,
        'Pending %': dash.health.pendingPct,
      } as Record<string, string | number>,
      filters: JSON.parse(JSON.stringify(query)) as Record<string, string | undefined>,
      footer: [
        'Generated by AI Bank Reconciliation Tool',
        'AI-assisted findings are advisory and require accountant review.',
      ],
    };
  }

  @Get('dashboard')
  @UseGuards(JwtAuthGuard, CompanyQueryGuard, RolesGuard)
  dashboard(
    @Req() req: { user: RequestUser },
    @Query() query: DashboardQueryDto,
  ) {
    return this.reportsService.dashboard(req.user.id, query.companyId, query);
  }

  @Get('summary')
  @UseGuards(JwtAuthGuard, CompanyQueryGuard, RolesGuard)
  async summary(
    @Req() req: { user: RequestUser },
    @Query() query: DashboardQueryDto,
  ) {
    const dash = await this.reportsService.dashboard(
      req.user.id,
      query.companyId,
      query,
    );
    return { kpis: dash.kpis, amounts: dash.amounts, health: dash.health };
  }

  @Get('status')
  @UseGuards(JwtAuthGuard, CompanyQueryGuard, RolesGuard)
  status(
    @Req() req: { user: RequestUser },
    @Query() query: DashboardQueryDto,
  ) {
    return this.reportsService.dashboard(req.user.id, query.companyId, query).then(
      (d) => ({ statusChart: d.statusChart, reviewChart: d.reviewChart }),
    );
  }

  @Get('review-outcomes')
  @UseGuards(JwtAuthGuard, CompanyQueryGuard, RolesGuard)
  reviewOutcomes(
    @Req() req: { user: RequestUser },
    @Query() query: DashboardQueryDto,
  ) {
    return this.reportsService.dashboard(req.user.id, query.companyId, query).then(
      (d) => ({ reviewChart: d.reviewChart, kpis: d.kpis }),
    );
  }

  @Get('monthly-trend')
  @UseGuards(JwtAuthGuard, CompanyQueryGuard, RolesGuard)
  monthlyTrend(
    @Req() req: { user: RequestUser },
    @Query() query: DashboardQueryDto,
  ) {
    return this.reportsService.monthlyTrend(req.user.id, query.companyId, query);
  }

  @Get('bank-accounts')
  @UseGuards(JwtAuthGuard, CompanyQueryGuard, RolesGuard)
  bankAccounts(
    @Req() req: { user: RequestUser },
    @Query() query: DashboardQueryDto,
  ) {
    return this.reportsService.bankAccountSummary(req.user.id, query.companyId, query);
  }

  @Get('party-exceptions')
  @UseGuards(JwtAuthGuard, CompanyQueryGuard, RolesGuard)
  partyExceptions(
    @Req() req: { user: RequestUser },
    @Query() query: DashboardQueryDto,
  ) {
    return this.reportsService.partyExceptions(req.user.id, query.companyId, query);
  }

  @Get('ai-summary')
  @UseGuards(JwtAuthGuard, CompanyQueryGuard, RolesGuard)
  aiSummary(
    @Req() req: { user: RequestUser },
    @Query() query: CompanyQueryDto,
  ) {
    return this.reportsService.aiSummary(req.user.id, query.companyId);
  }

  @Get('export/reconciliation.xlsx')
  @UseGuards(JwtAuthGuard, CompanyQueryGuard, RolesGuard)
  @Throttle({ default: { limit: 10, ttl: 60_000 } })
  async exportReconciliationXlsx(
    @Req() req: { user: RequestUser },
    @Query() query: DashboardQueryDto,
    @Res() res: Response,
  ) {
    const [bundle, dash] = await Promise.all([
      this.reportsService.exportRows(req.user.id, query.companyId, query),
      this.reportsService.dashboard(req.user.id, query.companyId, query),
    ]);
    const wb = buildWorkbook({
      companyName: bundle.companyName,
      rows: bundle.rows,
      aiRows: bundle.aiRows,
      reviewRows: bundle.reviewRows,
      summary: {
        'Total Bank Transactions': dash.kpis.totalBankTransactions,
        'Total Tally Transactions': dash.kpis.totalTallyTransactions,
        'Matched': dash.kpis.matched,
        'Unmatched': dash.kpis.unmatched,
        'Pending Review': dash.kpis.pendingReview,
      },
      filters: JSON.parse(JSON.stringify(query)) as Record<string, string | undefined>,
      footer: [
        'Generated by AI Bank Reconciliation Tool',
        'AI-assisted findings are advisory and require accountant review.',
      ],
    });
    await this.reportsService.auditExport(
      req.user.id,
      query.companyId,
      'RECONCILIATION',
      'XLSX',
      query,
    );
    res.setHeader(
      'Content-Type',
      'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
    );
    res.setHeader(
      'Content-Disposition',
      'attachment; filename="reconciliation.xlsx"',
    );
    res.send(wb);
  }

  @Get('export/exceptions.xlsx')
  @UseGuards(JwtAuthGuard, CompanyQueryGuard, RolesGuard)
  @Throttle({ default: { limit: 10, ttl: 60_000 } })
  async exportExceptionsXlsx(
    @Req() req: { user: RequestUser },
    @Query() query: DashboardQueryDto,
    @Res() res: Response,
  ) {
    const [bundle, dash] = await Promise.all([
      this.reportsService.exportRows(req.user.id, query.companyId, query),
      this.reportsService.dashboard(req.user.id, query.companyId, query),
    ]);
    const wb = buildExceptionsWorkbook({
      companyName: bundle.companyName,
      rows: bundle.rows,
      aiRows: bundle.aiRows,
      reviewRows: bundle.reviewRows,
      summary: {
        'Exceptions': dash.kpis.reviewRequired + dash.kpis.amountMismatch + dash.kpis.dateMismatch + dash.kpis.missingInTally + dash.kpis.missingInBank,
        'Unmatched': dash.kpis.unmatched,
      },
      filters: JSON.parse(JSON.stringify(query)) as Record<string, string | undefined>,
      footer: [
        'Generated by AI Bank Reconciliation Tool',
        'AI-assisted findings are advisory and require accountant review.',
      ],
    });
    await this.reportsService.auditExport(
      req.user.id,
      query.companyId,
      'EXCEPTIONS',
      'XLSX',
      query,
    );
    res.setHeader(
      'Content-Type',
      'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
    );
    res.setHeader(
      'Content-Disposition',
      'attachment; filename="exceptions.xlsx"',
    );
    res.send(wb);
  }

  @Get('export/reconciliation.pdf')
  @UseGuards(JwtAuthGuard, CompanyQueryGuard, RolesGuard)
  @Throttle({ default: { limit: 10, ttl: 60_000 } })
  async exportReconciliationPdf(
    @Req() req: { user: RequestUser },
    @Query() query: DashboardQueryDto,
    @Res() res: Response,
  ) {
    const bundle = await this.summaryBundle(req.user.id, query);
    const pdf = await buildSummaryPdf(bundle);
    await this.reportsService.auditExport(
      req.user.id,
      query.companyId,
      'RECONCILIATION',
      'PDF',
      query,
    );
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader(
      'Content-Disposition',
      'attachment; filename="reconciliation.pdf"',
    );
    res.send(pdf);
  }

  @Get('export/exceptions.pdf')
  @UseGuards(JwtAuthGuard, CompanyQueryGuard, RolesGuard)
  @Throttle({ default: { limit: 10, ttl: 60_000 } })
  async exportExceptionsPdf(
    @Req() req: { user: RequestUser },
    @Query() query: DashboardQueryDto,
    @Res() res: Response,
  ) {
    const [bundle, dash] = await Promise.all([
      this.reportsService.exportRows(req.user.id, query.companyId, query),
      this.reportsService.dashboard(req.user.id, query.companyId, query),
    ]);
    const pdf = await buildExceptionPdf({
      companyName: bundle.companyName,
      rows: bundle.rows,
      aiRows: bundle.aiRows,
      reviewRows: bundle.reviewRows,
      summary: {
        'Total Bank Transactions': dash.kpis.totalBankTransactions,
        'Total Tally Transactions': dash.kpis.totalTallyTransactions,
        'Matched': dash.kpis.matched,
        'Unmatched': dash.kpis.unmatched,
        'Exceptions': dash.kpis.reviewRequired + dash.kpis.amountMismatch + dash.kpis.dateMismatch + dash.kpis.missingInTally + dash.kpis.missingInBank,
        'Pending Review': dash.kpis.pendingReview,
        'Bank Amount': formatINR(dash.amounts.totalBank),
        'Tally Amount': formatINR(dash.amounts.totalTally),
        'Difference': formatINR(
          (Number(dash.amounts.totalBank) - Number(dash.amounts.totalTally)).toFixed(2),
        ),
      },
      filters: JSON.parse(JSON.stringify(query)) as Record<string, string | undefined>,
      footer: [
        'Generated by AI Bank Reconciliation Tool',
        'AI-assisted findings are advisory and require accountant review.',
      ],
    });
    await this.reportsService.auditExport(
      req.user.id,
      query.companyId,
      'EXCEPTIONS',
      'PDF',
      query,
    );
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader(
      'Content-Disposition',
      'attachment; filename="exceptions.pdf"',
    );
    res.send(pdf);
  }

  @Get('export/review.pdf')
  @UseGuards(JwtAuthGuard, CompanyQueryGuard, RolesGuard)
  @Throttle({ default: { limit: 10, ttl: 60_000 } })
  async exportReviewPdf(
    @Req() req: { user: RequestUser },
    @Query() query: DashboardQueryDto,
    @Res() res: Response,
  ) {
    const bundle = await this.summaryBundle(req.user.id, query);
    const rows = await this.reportsService.exportRows(
      req.user.id,
      query.companyId,
      query,
    );
    const pdf = await buildReviewPdf({
      ...bundle,
      reviewRows: rows.reviewRows,
    });
    await this.reportsService.auditExport(
      req.user.id,
      query.companyId,
      'REVIEW',
      'PDF',
      query,
    );
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', 'attachment; filename="review.pdf"');
    res.send(pdf);
  }
}
